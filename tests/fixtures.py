"""Shared deterministic fixtures for the streamnorm test-suite.

Everything is generated by fixed-seed code in this repository — no external
data, no system Unicode tables.
"""

import random

from streamnorm import CharacterTable

# Hand-written tiny table -----------------------------------------------
# A, B are starters; M1/M2/M5 share ccc 230, M3 has ccc 220, M4 has ccc 210.
# M1, M4 and M5 deliberately have no composition with A (blocking probes).
A = 0x41
B = 0x42
M1 = 0xE000  # ccc 230, never composes
M2 = 0xE001  # ccc 230
M3 = 0xE002  # ccc 220
M4 = 0xE003  # ccc 210, never composes
M5 = 0xE004  # ccc 230, never composes
X_A_M2 = 0xE100   # A + M2
X_A_M3 = 0xE101   # A + M3
X_AM3_M2 = 0xE102  # (A + M3) + M2 — recursive decomposition depth 2

TINY_DECOMP = {
    X_A_M2: (A, M2),
    X_A_M3: (A, M3),
    X_AM3_M2: (X_A_M3, M2),
}
TINY_CCC = {M1: 230, M2: 230, M3: 220, M4: 210, M5: 230}
TINY_COMP = {
    (A, M2): X_A_M2,
    (A, M3): X_A_M3,
    (X_A_M3, M2): X_AM3_M2,
}


def tiny_table():
    return CharacterTable(TINY_DECOMP, TINY_CCC, TINY_COMP)


def make_generated_table(seed=20260922):
    """Deterministic pseudo-random but well-formed table.

    Returns ``(table, decompositions, ccc, compositions, alphabet)`` where
    ``alphabet`` lists every code point usable to build test strings.
    Composition first elements are always starters and decomposition
    expansions always start with a starter, which keeps the table
    idempotency-safe (see README).
    """
    rng = random.Random(seed)
    starters = [0x41 + i for i in range(6)]            # A..F
    marks = [0xE000 + i for i in range(5)]
    ccc = {m: rng.choice([1, 200, 220, 230, 240]) for m in marks}
    decomp = {}
    comp = {}
    composites = []
    next_cp = 0xE100
    for s in starters:
        for m in marks:
            if rng.random() < 0.4:
                decomp[next_cp] = (s, m)
                comp[(s, m)] = next_cp
                composites.append(next_cp)
                next_cp += 1
    level2 = []
    for c in composites:
        _, tail_mark = decomp[c]
        for m in marks:
            # Well-formedness: the appended mark's ccc must not be smaller
            # than the tail mark's, so the expansion is already in
            # canonical order and every composite round-trips (the same
            # property real NFC tables have).
            if ccc[m] < ccc[tail_mark]:
                continue
            if rng.random() < 0.2:
                decomp[next_cp] = (c, m)
                comp[(c, m)] = next_cp
                level2.append(next_cp)
                next_cp += 1
    alphabet = starters + marks + composites + level2
    table = CharacterTable(decomp, ccc, comp)
    return table, decomp, ccc, comp, alphabet
